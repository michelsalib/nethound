// Package manager files for a published release, from its SHA256SUMS:
//   bun scripts/packages.ts 0.2.0 [SHA256SUMS] [out]
// Without a SHA256SUMS path, it is downloaded from the GitHub release. Writes, under out (default
// dist/packages): a Homebrew formula (Formula/nethound.rb), a Scoop manifest (nethound.json) and a
// winget manifest (manifests/m/MichelSalib/nethound/VERSION/), all installing the standalone binaries.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import pkg from "../package.json" with { type: "json" };

const REPO = "michelsalib/nethound";

export interface PackageFiles {
	[path: string]: string;
}

/** The hash SHA256SUMS lists for `name`, as sha256sum prints it. */
export function sumFor(sums: string, name: string): string | undefined {
	for (const line of sums.split(/\r?\n/)) {
		const [sum, file] = line.trim().split(/\s+/, 2);
		if (file === name || file === `*${name}`) return sum?.toLowerCase();
	}
	return undefined;
}

/** Every file, by path under the output directory. */
export function packageFiles(version: string, sums: string): PackageFiles {
	const base = `https://github.com/${REPO}/releases/download/v${version}`;
	const sum = (file: string) => {
		const s = sumFor(sums, file);
		if (!s) throw new Error(`SHA256SUMS has no entry for ${file}`);
		return s;
	};
	const bin = (file: string) =>
		`      url "${base}/${file}"\n      sha256 "${sum(file)}"`;
	const formula = `# Generated by scripts/packages.ts from the v${version} release's SHA256SUMS.
class Nethound < Formula
  desc "${pkg.description}"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${bin("nethound-darwin-arm64")}
    end
    on_intel do
${bin("nethound-darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${bin("nethound-linux-arm64")}
    end
    on_intel do
${bin("nethound-linux-x64")}
    end
  end

  def install
    bin.install Dir["nethound-*"].first => "nethound"
    # a release file, downloaded as is: not executable yet
    chmod 0755, bin/"nethound"
    # zsh's completion is meant for eval in ~/.zshrc, not for fpath
    generate_completions_from_executable(bin/"nethound", "completion", shells: [:bash, :fish])
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/nethound --version").strip
    # reads the machine, asks no one: fine in brew's sandbox
    assert_match '"kind": "loopback"', shell_output("#{bin}/nethound route 127.0.0.1 --json --no-docker")
    assert_match "nethound __complete", shell_output("#{bin}/nethound completion bash")
  end
end
`;

	const exe = "nethound-windows-x64.exe";
	const scoop = {
		version,
		description: pkg.description,
		homepage: `https://github.com/${REPO}`,
		license: "MIT",
		architecture: {
			"64bit": {
				url: `${base}/${exe}#/nethound.exe`,
				hash: sum(exe),
			},
		},
		bin: "nethound.exe",
		checkver: { github: `https://github.com/${REPO}` },
		autoupdate: {
			architecture: {
				"64bit": {
					url: `https://github.com/${REPO}/releases/download/v$version/${exe}#/nethound.exe`,
					hash: { url: "$baseurl/SHA256SUMS" },
				},
			},
		},
	};

	const id = "MichelSalib.nethound";
	const dir = `manifests/m/MichelSalib/nethound/${version}`;
	const head = (type: string) =>
		`# Generated by scripts/packages.ts from the v${version} release's SHA256SUMS.
# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.1.9.0.schema.json
PackageIdentifier: ${id}
PackageVersion: ${version}
`;
	const winget = {
		[`${dir}/${id}.yaml`]: `${head("version")}DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.9.0
`,
		[`${dir}/${id}.installer.yaml`]: `${head("installer")}InstallerType: portable
Commands:
  - nethound
Installers:
  - Architecture: x64
    InstallerUrl: ${base}/${exe}
    InstallerSha256: ${sum(exe).toUpperCase()}
ManifestType: installer
ManifestVersion: 1.9.0
`,
		[`${dir}/${id}.locale.en-US.yaml`]: `${head("defaultLocale")}PackageLocale: en-US
Publisher: Michel Salib
PublisherUrl: https://github.com/michelsalib
PackageName: nethound
PackageUrl: https://github.com/${REPO}
License: MIT
LicenseUrl: https://github.com/${REPO}/blob/main/LICENSE
ShortDescription: ${pkg.description}
Tags:
  - network
  - ports
  - netstat
  - cli
ReleaseNotesUrl: https://github.com/${REPO}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: 1.9.0
`,
	};

	return {
		"Formula/nethound.rb": formula,
		"nethound.json": `${JSON.stringify(scoop, null, 2)}\n`,
		...winget,
	};
}

async function download(url: string): Promise<string> {
	const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
	if (!res.ok) throw new Error(`could not download ${url}: HTTP ${res.status}`);
	return res.text();
}

if (import.meta.main) {
	const [version, sumsFile, out = join("dist", "packages")] =
		process.argv.slice(2);
	if (!version || !/^\d+\.\d+\.\d+$/.test(version)) {
		console.error("usage: bun scripts/packages.ts VERSION [SHA256SUMS] [OUT]");
		process.exit(2);
	}
	const sums = sumsFile
		? readFileSync(sumsFile, "utf8")
		: await download(
				`https://github.com/${REPO}/releases/download/v${version}/SHA256SUMS`,
			);
	for (const [path, text] of Object.entries(packageFiles(version, sums))) {
		const file = join(out, path);
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, text);
		console.log(file);
	}
}
